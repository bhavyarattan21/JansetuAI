export function getPortalForCategory(categoryId) {
  const norm = (categoryId || "").toLowerCase();
  for (const [key, val] of Object.entries(categoryPortalMap)) {
    if (norm.includes(key)) return val;
  }
  return {
    portal: officialPortals.cpgrams,
    stateAlternative: officialPortals.haryanaCmWindow,
    typicalResolutionDays: 7,
    department: "District Grievance Redressal Cell / Municipal Corporation",
    departmentHi: "जिला लोक शिकायत निवारण प्रकोष्ठ",
    documentsNeeded: ["Detailed description", "Proof/photo of issue", "Valid identification (Aadhaar/Voter ID)"]
  };
}
